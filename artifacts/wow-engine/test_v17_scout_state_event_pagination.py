def test_over_budget_stream_is_rejected_before_appending_a_new_page():
    """At 50,000 events query only one overflow witness, then HOLD."""
    class Infinite:
        def __init__(self):
            self.after = 0
            self.page_limit = 1000
            self.last_requested_limit = None

        def table(self, _name):
            return self
        def select(self, _columns):
            return self
        def eq(self, *_args):
            return self
        def gt(self, _field, after):
            self.after = after
            return self
        def order(self, _field):
            return self
        def limit(self, n):
            self.page_limit = n
            self.last_requested_limit = n
            return self
        def execute(self):
            return SimpleNamespace(data=[
                {"event_id": n, "state": "SPECIALIST_PROCESSING"}
                for n in range(self.after + 1, self.after + self.page_limit + 1)
            ])

    infinite = Infinite()
    with pytest.raises(RuntimeError, match="SCOUT_STATE_EVENT_PAGINATION_INVALID"):
        _read_all_state_events(infinite, "wow-scout-20261031")
    assert infinite.last_requested_limit == 1


def test_query_budget_prevents_unbounded_single_row_reads():
    """Slow one-event pages fail closed before 50,000 network round trips."""
    class OneRowPerPage:
        def __init__(self):
            self.after = 0
            self.calls = 0

        def table(self, _name):
            return self
        def select(self, _columns):
            return self
        def eq(self, *_args):
            return self
        def gt(self, _field, last_id):
            self.after = last_id
            return self
        def order(self, _field):
            return self
        def limit(self, _count):
            return self
        def execute(self):
            self.calls += 1
            return SimpleNamespace(data=[{
                "event_id": self.after + 1,
                "state": "SPECIALIST_PROCESSING",
            }])

    slow = OneRowPerPage()
    with pytest.raises(RuntimeError, match="SCOUT_STATE_EVENT_READ_BUDGET_EXCEEDED"):
        _read_all_state_events(slow, "wow-scout-20261031")
    assert slow.calls == 128


def test_missing_jobs_response_is_not_an_empty_accepted_ledger():
    client = _realistic_run()
    original = client.table

    def broken_table(name):
        query = original(name)
        if name == "wow_scout_handoff_jobs":
            query.execute = lambda: SimpleNamespace(data=None)
        return query

    client.table = broken_table
    with pytest.raises(RuntimeError, match="SCOUT_HANDOFF_JOBS_READ_INVALID"):
        read_run_summary(client, "wow-scout-20261031")
    assert client.event_pages == 0


