"""Evidence-only regression for complete Scout terminal event pagination.

Reproduces the actual Oct 31 417-job/2,499-event source.
The 416 terminal specialist outcomes are 306 MODEL_UNAVAILABLE HOLDs, 86
MODEL_INPUTS_INSUFFICIENT HOLDs and 24 LLP_EVENT_GOVERNANCE_NOT_PROVEN HOLDs. There are 416
SPECIALIST_PROCESSING events after the first 1,000 state events.
No fitted probability, wager or score is generated by these tests.
"""
from types import SimpleNamespace

import pytest

from v17.scout_handoff_queue import _read_all_state_events, read_run_summary


class _Query:
    def __init__(self, client, name):
        self.client = client
        self.name = name
        self.after = 0
        self.page_limit = 1000
        self.source = None

    def select(self, columns):
        if self.name == "wow_scout_handoff_state_events":
            assert columns == "event_id,candidate_id,target_lane,state,code,can_execute,created_at"
        return self

    def eq(self, name, value):
        assert name == "source_run_id"
        self.source = value
        return self

    def gt(self, field, value):
        assert field == "event_id"
        self.after = value
        return self

    def order(self, field):
        assert field in ("event_id", "created_at")
        return self

    def limit(self, count):
        self.page_limit = count
        return self

    def execute(self):
        assert self.source == self.client.expected_source_run_id
        if self.name == "wow_scout_handoff_state_events":
            self.client.event_pages += 1
            rows = [r for r in self.client.events if r["event_id"] > self.after]
            # Simulate an enforced server max_rows smaller than the requested
            # 1000, so stopping on len(batch) < 1000 would lose evidence.
            return SimpleNamespace(data=rows[: min(self.page_limit, 700)])
        assert self.name == "wow_scout_handoff_jobs"
        return SimpleNamespace(data=self.client.jobs)


class _Client:
    def __init__(self):
        self.events = []
        self.jobs = []
        self.event_pages = 0
        self.expected_source_run_id = "wow-scout-20261031"

    def table(self, name):
        return _Query(self, name)


def _realistic_run():
    client = _Client()
    for index in range(417):
        rejected = index == 416
        client.jobs.append({
            "candidate_id": f"candidate-{index}",
            "research_run_id": "research-20261031",
            "research_priority": "UNRANKED",
            "target_lane": "LLP_TEAM_BETTING_ENGINE",
            "current_state": "HANDOFF_BLOCKED" if rejected else "MODEL_EVALUATED",
            "terminal": True,
            "last_error_code": "TEAM_EVENT_IDENTITY_INCOMPLETE" if rejected else None,
            "specialist_receipt": {} if rejected else {
                "result": {"rows": [{
                    "terminal_status": "HELD",
                    "code": (
                        "MODEL_UNAVAILABLE" if index < 306 else
                        "MODEL_INPUTS_INSUFFICIENT" if index < 392 else
                        "LLP_EVENT_GOVERNANCE_NOT_PROVEN"
                    ),
                }]}
            },
        })
    for state, n in (
        ("DISCOVERED", 417),
        ("RESEARCH_INTEREST", 417),
        ("RED_TEAM_PASSED", 416),
        ("SPECIALIST_HANDOFF_QUEUED", 416),
        ("SPECIALIST_PROCESSING", 416),
        ("MODEL_EVALUATED", 416),
        ("HANDOFF_BLOCKED", 1),
    ):
        for index in range(n):
            client.events.append({
                "event_id": len(client.events) + 1,
                "candidate_id": f"candidate-{index if state != 'HANDOFF_BLOCKED' else 416}",
                "target_lane": "LLP_TEAM_BETTING_ENGINE",
                "state": state,
                "can_execute": False,
            })
    assert len(client.events) == 2499
    return client


def test_handoff_jobs_cannot_be_read_for_a_different_source():
    client = _realistic_run()
    with pytest.raises(AssertionError):
        read_run_summary(client, "other-scout-source")
    assert client.event_pages == 0


def test_large_terminal_scout_run_recovers_all_416_worker_events():
    client = _realistic_run()
    summary = read_run_summary(client, "wow-scout-20261031")
    assert client.event_pages >= 5
    assert summary["candidate_jobs"] == 417
    assert summary["specialist_processing_seen"] == 416
    assert summary["rows_in"] == 417
    assert summary["rows_rejected"] == 417
    assert summary["row_accounting_pass"] is True
    assert summary["reconciliation_pass"] is True
    assert summary["rows_completed"] == 0
    assert summary["can_execute"] is False


def test_small_server_page_cap_still_completes_full_ledger():
    """A provider cap well below 500 rows must not trigger an early HOLD."""
    client = _realistic_run()
    original_table = client.table

    def patched_table(name):
        query = original_table(name)
        original_execute = query.execute

        def capped():
            if name != "wow_scout_handoff_state_events":
                return original_execute()
            assert query.source == "wow-scout-20261031"
            client.event_pages += 1
            rows = [row for row in client.events if row["event_id"] > query.after]
            return SimpleNamespace(data=rows[:min(query.page_limit, 75)])
        query.execute = capped
        return query

    client.table = patched_table
    events = _read_all_state_events(client, "wow-scout-20261031")
    assert len(events) == 2499
    assert client.event_pages > 30


