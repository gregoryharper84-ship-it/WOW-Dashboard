"""Fitted scenario input bridge for opponent outcomes and player usage.

This module does not fit any sporting distribution or attest uploaded provenance.
All numerical inputs must be generated by the existing fitted specialists and
frozen before kickoff. No model promotion, production scoring, or execution.
"""
from __future__ import annotations

from datetime import datetime, timezone
from math import fsum, isfinite
import re
from typing import Any, Mapping

CAN_EXECUTE = False
AUTOMATIC_PROMOTION = False
TERMINAL_AUTHORITY = "V17_TERMINAL_REDUCER"
PROBABILITY_PUBLISHABLE = False
_SHA = re.compile(r"[0-9a-f]{64}\Z")
_VALID_STATES = {"LEADING", "TIED", "TRAILING"}
_VALID_SPACES = {
    "TWO_WAY_FULL_GAME_OVERTIME": {"HOME", "AWAY"},
    "THREE_WAY_REGULATION": {"HOME", "AWAY", "DRAW"},
}
_BASIS = {"TWO_WAY_FULL_GAME_OVERTIME": "FULL_GAME_OVERTIME",
          "THREE_WAY_REGULATION": "REGULATION_ONLY"}


def _base(status: str, **kwargs: Any) -> dict[str, Any]:
    return {"status": status, "can_execute": CAN_EXECUTE,
            "automatic_promotion": AUTOMATIC_PROMOTION,
            "terminal_authority": TERMINAL_AUTHORITY,
            "probability_publishable": PROBABILITY_PUBLISHABLE,
            "joint_model_certified": False, "source_authentication": "NOT_INDEPENDENTLY_VERIFIED",
            **kwargs}


def _dt(value: Any) -> datetime | None:
    if not isinstance(value, str):
        return None
    try:
        dt = datetime.fromisoformat(value.replace("Z", "+00:00"))
        return dt.astimezone(timezone.utc) if dt.tzinfo else None
    except (ValueError, OverflowError):
        return None


def _finite(value: Any, low: float = 0.0, high: float | None = None) -> float | None:
    if type(value) not in (float, int):
        return None
    try:
        n = float(value)
    except (ValueError, TypeError, OverflowError):
        return None
    return n if isfinite(n) and n >= low and (high is None or n <= high) else None


def _ident(s: Mapping[str, Any]) -> tuple[str, str] | None:
    sport, event = s.get("sport"), s.get("official_event_id")
    if not isinstance(sport, str) or not sport.strip() or not isinstance(event, str) or not event.strip():
        return None
    return (sport.strip().upper(), event.strip())


def _sha(value: Any) -> bool:
    return isinstance(value, str) and _SHA.fullmatch(value) is not None


def _validated(snapshot: Mapping[str, Any]) -> tuple[list[dict[str, Any]], str] | None:
    if not isinstance(snapshot, Mapping) or _ident(snapshot) is None:
        return None
    t = _dt(snapshot.get("snapshot_at_utc"))
    event = _dt(snapshot.get("event_start_utc"))
    fit = _dt(snapshot.get("scenario_fit_cutoff_utc"))
    space = snapshot.get("outcome_space")
    if (t is None or event is None or fit is None or not (fit <= t < event)
            or not _sha(snapshot.get("scenario_model_artifact_sha256"))
            or not _sha(snapshot.get("feature_manifest_sha256"))
            or not isinstance(snapshot.get("scenario_receipt_id"), str)
            or not snapshot["scenario_receipt_id"].strip()
            or not isinstance(space, str) or space not in _VALID_SPACES
            or snapshot.get("favorite_side") not in ("HOME", "AWAY")):
        return None
    rows = snapshot.get("scenarios")
    if not isinstance(rows, (list, tuple)) or not rows or len(rows) > 10000:
        return None
    seen: set[str] = set()
    checked: list[dict[str, Any]] = []
    for row in rows:
        if not isinstance(row, Mapping):
            return None
        ident, outcome = row.get("scenario_id"), row.get("outcome")
        w = _finite(row.get("weight"), 0, 1)
        if (not isinstance(ident, str) or not ident.strip() or ident != ident.strip() or ident in seen
                or not isinstance(outcome, str) or outcome not in _VALID_SPACES[space]
                or not isinstance(row.get("home_game_state"), str) or row.get("home_game_state") not in _VALID_STATES
                or not isinstance(row.get("away_game_state"), str) or row.get("away_game_state") not in _VALID_STATES
                or w is None or w <= 0):
            return None
        seen.add(ident)
        checked.append({"scenario_id": ident, "outcome": outcome,
                        "home_game_state": row["home_game_state"],
                        "away_game_state": row["away_game_state"], "weight": w})
    if abs(fsum(r["weight"] for r in checked) - 1) > 1e-8:
        return None
    return checked, space


def evaluate_scenario_outcomes(snapshot: Mapping[str, Any]) -> dict[str, Any]:
    """Research mixture from externally fitted scenario rows, never odds."""
    invalid = _base("SCENARIO_INPUT_UNAVAILABLE", home_win_probability=None,
                    away_win_probability=None, draw_probability=None,
                    winner_research_argmax=None, opponent_upset_paths=[])
    validated = _validated(snapshot)
    if validated is None:
        return invalid
    rows, space = validated
    probabilities = {o: round(fsum(row["weight"] for row in rows if row["outcome"] == o), 12)
                     for o in ("HOME", "AWAY", "DRAW")}
    outcomes = ("HOME", "AWAY") if space == "TWO_WAY_FULL_GAME_OVERTIME" else ("HOME", "AWAY", "DRAW")
    leader = max(outcomes, key=lambda o: probabilities[o])
    underdog = "AWAY" if snapshot["favorite_side"] == "HOME" else "HOME"
    return _base("OPPONENT_SCENARIO_SHADOW", home_win_probability=probabilities["HOME"],
                 away_win_probability=probabilities["AWAY"], draw_probability=probabilities["DRAW"],
                 winner_research_argmax=leader, opponent_upset_paths=[r["scenario_id"] for r in rows if r["outcome"] == underdog],
                 scenario_count=len(rows), scenario_receipt_id=snapshot["scenario_receipt_id"],
                 scenario_model_artifact_sha256=snapshot["scenario_model_artifact_sha256"],
                 source_model="EXTERNALLY_FITTED_SCENARIO_INPUT", ranking_eligible=False)


def evaluate_player_usage(snapshot: Mapping[str, Any], prop: Mapping[str, Any]) -> dict[str, Any]:
    """Mix already-fitted scenario-specific exact-line distributions."""
    invalid = _base("PLAYER_EVIDENCE_UNAVAILABLE", expected_count=None, variance=None,
                    p_over_exact_line=None, ranking_eligible=False)
    checked = _validated(snapshot)
    if checked is None or not isinstance(prop, Mapping) or _ident(snapshot) != _ident(prop):
        return invalid
    rows, space = checked
    line = _finite(prop.get("exact_line"), 0)
    fit = _dt(prop.get("prop_fit_cutoff_utc"))
    snapshot_at = _dt(snapshot["snapshot_at_utc"])
    if (line is None or fit is None or not fit <= snapshot_at
            or not isinstance(prop.get("player_id"), str) or not prop["player_id"].strip()
            or not isinstance(prop.get("market_id"), str) or not prop["market_id"].strip()
            or not _sha(prop.get("prop_fit_artifact_sha256"))
            or not _sha(prop.get("prop_source_manifest_sha256"))
            or prop.get("settlement_basis") != _BASIS[space]):
        return invalid
    supplied = prop.get("scenario_counts")
    if not isinstance(supplied, (list, tuple)) or len(supplied) != len(rows):
        return invalid
    counts: dict[str, tuple[float, float, float]] = {}
    for item in supplied:
        if not isinstance(item, Mapping):
            return invalid
        sid = item.get("scenario_id")
        mean = _finite(item.get("expected_count"), 0)
        var = _finite(item.get("count_variance"), 0)
        tail = _finite(item.get("p_over_exact_line"), 0, 1)
        if not isinstance(sid, str) or sid in counts or None in (mean, var, tail):
            return invalid
        counts[sid] = (mean, var, tail)
    if set(counts) != {r["scenario_id"] for r in rows}:
        return invalid
    try:
        expected = fsum(r["weight"] * counts[r["scenario_id"]][0] for r in rows)
        variance = fsum(r["weight"] * (counts[r["scenario_id"]][1]
                         + (counts[r["scenario_id"]][0] - expected) ** 2) for r in rows)
        tail = fsum(r["weight"] * counts[r["scenario_id"]][2] for r in rows)
    except (OverflowError, ValueError):
        return invalid
    if not all(isfinite(moment) for moment in (expected, variance, tail)):
        return invalid
    return _base("PLAYER_USAGE_SHADOW", expected_count=expected, variance=variance,
                 p_over_exact_line=tail, player_id=prop["player_id"], exact_line=line,
                 scenario_count=len(rows), ranking_eligible=False,
                 game_script_source="FROZEN_FITTED_TEAM_EVENT_SCENARIOS")
