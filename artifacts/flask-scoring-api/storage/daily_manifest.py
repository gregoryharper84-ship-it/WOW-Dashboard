def terminalize_run(
    *,
    run_id: str,
    finished_at: str,
    run_status: str,
    failure_reason: str | None = None,
    failure_module: str | None = None,
    reconciliation: dict | None = None,
    execution_owner: str | None = None,
) -> bool:
    """Close an accepted/in-progress run exactly once."""
    conn = _get_conn()
    try:
        with conn:
            with conn.cursor() as cur:
                owner_fence = ""
                params: list[Any] = [
                    finished_at,
                    run_status,
                    failure_reason or run_status,
                    failure_reason,
                    failure_module,
                    json.dumps(reconciliation) if reconciliation is not None else None,
                    run_id,
                ]
                if execution_owner is not None:
                    owner_fence = """
                      AND execution_owner = %s
                      AND lease_expires_at >= NOW()
                    """
                    params.append(execution_owner)
                cur.execute(
                    f"""
                    UPDATE wow_daily_runs
                    SET finished_at = %s,
                        run_status = %s,
                        progress_stage = 'TERMINAL',
                        progress_detail = %s,
                        progress_updated_at = NOW(),
                        failure_reason = %s,
                        failure_module = %s,
                        lease_expires_at = NOW(),
                        reconciliation = COALESCE(%s, reconciliation)
                    WHERE run_id = %s
                      AND finished_at IS NULL
                      AND run_status IN ('ACCEPTED', 'IN_PROGRESS')
                    {owner_fence}
                    """,
                    tuple(params),
                )
                return cur.rowcount == 1
    finally:
        conn.close()


def reap_expired_runs(
    *,
    now: str,
    include_executor_records: bool = False,
) -> int | list[dict[str, int | str | None]]:
    """Terminalize deadline-expired or heartbeat-orphaned headers honestly."""
    conn = _get_conn()
    try:
        with conn:
            with conn.cursor() as cur:
                cur.execute(
                    """
                    UPDATE wow_daily_runs
                    SET finished_at = %s,
                        run_status = 'DEGRADED',
                        progress_stage = 'TERMINAL',
                        progress_detail = CASE
                            WHEN deadline_at IS NOT NULL AND deadline_at < %s
                                THEN 'Whole-run deadline exceeded'
                            ELSE 'Detached runner heartbeat expired'
                        END,
                        progress_updated_at = NOW(),
                        failure_reason = CASE
                            WHEN deadline_at IS NOT NULL AND deadline_at < %s
                                THEN 'WHOLE_RUN_DEADLINE_EXCEEDED'
                            ELSE 'RUNNER_HEARTBEAT_EXPIRED'
                        END,
                        failure_module = 'daily_manifest.reap_expired_runs',
                        lease_expires_at = NOW()
                    WHERE finished_at IS NULL
                      AND run_status IN ('ACCEPTED', 'IN_PROGRESS')
                      AND (
                          (deadline_at IS NOT NULL AND deadline_at < %s)
                          OR (
                              run_status = 'IN_PROGRESS'
                              AND lease_expires_at IS NOT NULL
                              AND lease_expires_at < %s
                          )
                      )
                    RETURNING run_id, executor_pid
                    """,
                    (now, now, now, now, now),
                )
                if not include_executor_records:
                    return cur.rowcount
                return [
                    {"run_id": run_id, "executor_pid": executor_pid}
                    for run_id, executor_pid in cur.fetchall()
                ]
    finally:
        conn.close()


def finalize_run(
    *,
    run_id: str,
    finished_at: str,
    run_status: str,
    scanned_sports: list[str],
    missing_sports: list[str],
    failed_modules: list[str],
    total_discovered: int,
    source_union_counts: dict,
    reconciliation: dict,
    failure_reason: str | None = None,
    failure_module: str | None = None,
    completion_detail: str | None = None,
    orchestration_metadata: dict | None = None,
    execution_owner: str | None = None,
) -> bool:
    """Update run header with final state. Called after all rows are written."""
    try:
        conn = _get_conn()
        with conn:
            with conn.cursor() as cur:
                owner_fence = ""
                params: list[Any] = [
                    finished_at,
                    run_status,
                    json.dumps(scanned_sports),
                    json.dumps(missing_sports),
                    json.dumps(failed_modules),
                    total_discovered,
                    json.dumps(source_union_counts),
                    json.dumps(reconciliation),
                    completion_detail or run_status,
                    failure_reason,
                    failure_module,
                    (
                        json.dumps(orchestration_metadata, default=str)
                        if orchestration_metadata is not None else None
                    ),
                    run_id,
                ]
                if execution_owner is not None:
                    owner_fence = """
                      AND execution_owner = %s
                      AND lease_expires_at >= NOW()
                    """
                    params.append(execution_owner)
                cur.execute(
                    f"""
                    UPDATE wow_daily_runs SET
                        finished_at         = %s,
                        run_status          = %s,
                        scanned_sports      = %s,
                        missing_sports      = %s,
                        failed_modules      = %s,
                        total_discovered    = %s,
                        source_union_counts = %s,
                        reconciliation      = %s,
                        progress_stage      = 'TERMINAL',
                        progress_detail     = %s,
                        progress_updated_at = NOW(),
                        failure_reason      = %s,
                        failure_module      = %s,
                        orchestration_metadata = COALESCE(%s, orchestration_metadata),
                        lease_expires_at    = NOW()
                    WHERE run_id = %s
                      AND finished_at IS NULL
                      AND run_status IN ('ACCEPTED', 'IN_PROGRESS')
                    {owner_fence}
                    """,
                    tuple(params),
                )
                updated = cur.rowcount == 1
        conn.close()
        return updated
    except Exception as exc:
        logger.error("daily_manifest.finalize_run failed for %s: %s", run_id, exc)
        return False


