def get_run(run_id: str) -> dict | None:
    """Fetch run header by run_id. Returns None when not found."""
    try:
        conn = _get_conn()
        with conn.cursor() as cur:
            cur.execute(
                "SELECT * FROM wow_daily_runs WHERE run_id = %s LIMIT 1",
                (run_id,),
            )
            cols = [d[0] for d in cur.description]
            row = cur.fetchone()
        conn.close()
        if row is None:
            return None
        result = dict(zip(cols, row))
        for k in ("requested_sports", "scanned_sports", "missing_sports",
                  "failed_modules", "runtime_provenance", "source_union_counts",
                   "reconciliation", "discovery_checkpoint", "orchestration_metadata"):
            if isinstance(result.get(k), str):
                try:
                    result[k] = json.loads(result[k])
                except Exception:
                    pass
        return result
    except Exception as exc:
        logger.error("daily_manifest.get_run failed for %s: %s", run_id, exc)
        return None


