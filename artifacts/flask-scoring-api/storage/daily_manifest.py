"""
storage/daily_manifest.py — Immutable WOW Daily Run Manifest

Provides persistent, idempotent storage for canonical WOW Daily run records.

Tables
------
wow_daily_runs        — one row per canonical daily run (run_id PK)
wow_daily_run_rows    — one row per evaluated selection in a run

Design invariants
-----------------
- run_id is a UUID generated by the orchestrator before any evaluation begins.
- Rows are written once, never updated.  Reconciliation state is appended-only.
- A duplicate run_id write is an idempotent no-op (ON CONFLICT DO NOTHING).
- No selection write succeeds without a matching run header.
- can_execute = False (dry-run module; actual writes are driven by the route).
"""
from __future__ import annotations

import json
import os
import logging
import threading
from datetime import date, datetime, timezone
from typing import Any

import psycopg2

logger = logging.getLogger(__name__)

can_execute = False
MODULE_ID = "WOW-DAILY-MANIFEST-v1.0"
_DB_CONNECT_TIMEOUT_SECONDS = 5
_DB_STATEMENT_TIMEOUT_MS = 30_000
_DB_LOCK_TIMEOUT_MS = 5_000
_ACK_CONNECT_TIMEOUT_SECONDS = 2
_ACK_STATEMENT_TIMEOUT_MS = 3_000
_ACK_LOCK_TIMEOUT_MS = 1_000
_SCHEMA_ADVISORY_LOCK = 441_721_908
_schema_ready = False
_schema_lock = threading.Lock()
RUNNER_LEASE_SECONDS = 90

# ---------------------------------------------------------------------------
# DB connection helper (mirrors storage/results.py pattern)
# ---------------------------------------------------------------------------

def _get_conn(*, acknowledgement: bool = False):
    url = os.environ.get("DATABASE_URL", "")
    if not url:
        raise RuntimeError("DATABASE_URL not set")
    connect_timeout = (
        _ACK_CONNECT_TIMEOUT_SECONDS
        if acknowledgement else _DB_CONNECT_TIMEOUT_SECONDS
    )
    statement_timeout = (
        _ACK_STATEMENT_TIMEOUT_MS
        if acknowledgement else _DB_STATEMENT_TIMEOUT_MS
    )
    lock_timeout = (
        _ACK_LOCK_TIMEOUT_MS
        if acknowledgement else _DB_LOCK_TIMEOUT_MS
    )
    return psycopg2.connect(
        url,
        connect_timeout=connect_timeout,
        options=(
            f"-c statement_timeout={statement_timeout} "
            f"-c lock_timeout={lock_timeout}"
        ),
    )


