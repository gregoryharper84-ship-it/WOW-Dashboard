def ensure_tables() -> bool:
    """Create manifest tables once per process with cross-worker DDL safety."""
    global _schema_ready
    if _schema_ready:
        return True

    with _schema_lock:
        if _schema_ready:
            return True
        try:
            conn = _get_conn()
            with conn:
                with conn.cursor() as cur:
                    # DDL is only a bootstrap concern. Serialize it across
                    # gunicorn/process workers so duplicate POSTs never
                    # deadlock before their idempotency record is read.
                    cur.execute(
                        "SELECT pg_advisory_xact_lock(%s)",
                        (_SCHEMA_ADVISORY_LOCK,),
                    )
                    cur.execute(_SCHEMA_SQL)
                    cur.execute(
                        """
                        ALTER TABLE wow_daily_runs
                            ADD COLUMN IF NOT EXISTS idempotency_key TEXT,
                            ADD COLUMN IF NOT EXISTS run_timezone TEXT
                                NOT NULL DEFAULT 'UTC',
                            ADD COLUMN IF NOT EXISTS request_fingerprint TEXT,
                            ADD COLUMN IF NOT EXISTS deadline_at TIMESTAMPTZ,
                            ADD COLUMN IF NOT EXISTS progress_stage TEXT
                                NOT NULL DEFAULT 'ACCEPTED',
                            ADD COLUMN IF NOT EXISTS progress_detail TEXT,
                            ADD COLUMN IF NOT EXISTS progress_updated_at TIMESTAMPTZ,
                            ADD COLUMN IF NOT EXISTS failure_reason TEXT,
                            ADD COLUMN IF NOT EXISTS failure_module TEXT,
                            ADD COLUMN IF NOT EXISTS execution_owner TEXT,
                            ADD COLUMN IF NOT EXISTS executor_pid INTEGER,
                            ADD COLUMN IF NOT EXISTS lease_expires_at TIMESTAMPTZ,
                            ADD COLUMN IF NOT EXISTS last_heartbeat_at TIMESTAMPTZ,
                            ADD COLUMN IF NOT EXISTS discovery_checkpoint JSONB,
                            ADD COLUMN IF NOT EXISTS orchestration_metadata JSONB
                        """
                    )
                    # A run that is interrupted before discovery has no honest
                    # candidate total. Preserve NULL as "not finalized" rather
                    # than serializing a synthetic zero.
                    cur.execute(
                        """
                        ALTER TABLE wow_daily_runs
                            ALTER COLUMN total_discovered DROP NOT NULL,
                            ALTER COLUMN total_discovered DROP DEFAULT
                        """
                    )
                    cur.execute(
                        """
                        CREATE UNIQUE INDEX IF NOT EXISTS
                            uq_wow_daily_runs_idempotency_key
                        ON wow_daily_runs (idempotency_key)
                        WHERE idempotency_key IS NOT NULL
                        """
                    )
            conn.close()
            _schema_ready = True
            return True
        except Exception as exc:
            logger.error("daily_manifest.ensure_tables failed: %s", exc)
            return False


