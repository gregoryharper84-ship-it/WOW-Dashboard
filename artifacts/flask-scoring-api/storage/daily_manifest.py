def create_run(
    *,
    run_id: str,
    run_date: str,
    started_at: str,
    environment: str,
    requested_sports: list[str],
    session_id: str | None = None,
    runtime_provenance: dict | None = None,
) -> bool:
    """
    Insert the run header row.  Idempotent — duplicate run_id is a no-op.
    Returns True on success, False on failure.
    """
    try:
        conn = _get_conn()
        with conn:
            with conn.cursor() as cur:
                cur.execute(
                    """
                    INSERT INTO wow_daily_runs
                        (run_id, run_date, started_at, environment,
                         requested_sports, session_id, runtime_provenance)
                    VALUES (%s, %s, %s, %s, %s, %s, %s)
                    ON CONFLICT (run_id) DO NOTHING
                    """,
                    (
                        run_id,
                        run_date,
                        started_at,
                        environment,
                        json.dumps(requested_sports),
                        session_id,
                        json.dumps(runtime_provenance) if runtime_provenance else None,
                    ),
                )
        conn.close()
        return True
    except Exception as exc:
        logger.error("daily_manifest.create_run failed for %s: %s", run_id, exc)
        return False


def finalize_run(
    *,
    run_id: str,
    finished_at: str,
    run_status: str,
    scanned_sports: list[str],
    missing_sports: list[str],
    failed_modules: list[str],
    total_discovered: int,
    source_union_counts: dict,
    reconciliation: dict,
) -> bool:
    """Update run header with final state. Called after all rows are written."""
    try:
        conn = _get_conn()
        with conn:
            with conn.cursor() as cur:
                cur.execute(
                    """
                    UPDATE wow_daily_runs SET
                        finished_at         = %s,
                        run_status          = %s,
                        scanned_sports      = %s,
                        missing_sports      = %s,
                        failed_modules      = %s,
                        total_discovered    = %s,
                        source_union_counts = %s,
                        reconciliation      = %s
                    WHERE run_id = %s
                    """,
                    (
                        finished_at,
                        run_status,
                        json.dumps(scanned_sports),
                        json.dumps(missing_sports),
                        json.dumps(failed_modules),
                        total_discovered,
                        json.dumps(source_union_counts),
                        json.dumps(reconciliation),
                        run_id,
                    ),
                )
        conn.close()
        return True
    except Exception as exc:
        logger.error("daily_manifest.finalize_run failed for %s: %s", run_id, exc)
        return False


