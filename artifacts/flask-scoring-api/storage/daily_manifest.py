def get_run(run_id: str) -> dict | None:
    """Fetch run header by run_id. Returns None when not found."""
    try:
        conn = _get_conn()
        with conn.cursor() as cur:
            cur.execute(
                "SELECT * FROM wow_daily_runs WHERE run_id = %s LIMIT 1",
                (run_id,),
            )
            cols = [d[0] for d in cur.description]
            row = cur.fetchone()
        conn.close()
        if row is None:
            return None
        result = dict(zip(cols, row))
        for k in ("requested_sports", "scanned_sports", "missing_sports",
                  "failed_modules", "runtime_provenance", "source_union_counts",
                  "reconciliation"):
            if isinstance(result.get(k), str):
                try:
                    result[k] = json.loads(result[k])
                except Exception:
                    pass
        return result
    except Exception as exc:
        logger.error("daily_manifest.get_run failed for %s: %s", run_id, exc)
        return None


def get_run_rows(run_id: str, limit: int = 500) -> list[dict]:
    """Fetch all evaluated rows for a run. Returns [] on failure."""
    try:
        conn = _get_conn()
        with conn.cursor() as cur:
            cur.execute(
                """
                SELECT run_id, canonical_selection_id, market_version_id,
                       sport, player, prop, side, line, game_date,
                       terminal_bucket, classification, wow_score,
                       final_approval_blocker, audit_valid, side_resolution,
                       reconciliation_status, created_at
                FROM wow_daily_run_rows
                WHERE run_id = %s
                ORDER BY sport, player, prop, side
                LIMIT %s
                """,
                (run_id, limit),
            )
            cols = [d[0] for d in cur.description]
            rows = [dict(zip(cols, r)) for r in cur.fetchall()]
        conn.close()
        return rows
    except Exception as exc:
        logger.error("daily_manifest.get_run_rows failed for %s: %s", run_id, exc)
        return []


def list_runs(run_date: str | None = None, limit: int = 10) -> list[dict]:
    """List recent run headers. Optionally filter by date."""
    try:
        conn = _get_conn()
        with conn.cursor() as cur:
            if run_date:
                cur.execute(
                    """
                    SELECT run_id, run_date, started_at, finished_at,
                           environment, run_status, total_discovered,
                           requested_sports, scanned_sports, missing_sports
                    FROM wow_daily_runs
                    WHERE run_date = %s
                    ORDER BY started_at DESC LIMIT %s
                    """,
                    (run_date, limit),
                )
            else:
                cur.execute(
                    """
                    SELECT run_id, run_date, started_at, finished_at,
                           environment, run_status, total_discovered,
                           requested_sports, scanned_sports, missing_sports
                    FROM wow_daily_runs
                    ORDER BY started_at DESC LIMIT %s
                    """,
                    (limit,),
                )
            cols = [d[0] for d in cur.description]
            rows = [dict(zip(cols, r)) for r in cur.fetchall()]
        conn.close()
        for r in rows:
            for k in ("requested_sports", "scanned_sports", "missing_sports"):
                if isinstance(r.get(k), str):
                    try:
                        r[k] = json.loads(r[k])
                    except Exception:
                        pass
        return rows
    except Exception as exc:
        logger.error("daily_manifest.list_runs failed: %s", exc)
        return []
