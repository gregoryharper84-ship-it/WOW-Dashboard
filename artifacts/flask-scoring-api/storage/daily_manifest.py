def save_run_row(
    *,
    run_id: str,
    canonical_selection_id: str,
    market_version_id: str | None,
    run_date: str,
    sport: str,
    player: str,
    prop: str,
    side: str,
    line: float,
    game_date: str | None,
    terminal_bucket: str | None,
    classification: str | None,
    wow_score: float | None,
    final_approval_blocker: str | None,
    audit_valid: bool | None,
    side_resolution: str | None,
    reconciliation_status: str | None,
    full_row: dict,
) -> bool:
    """
    Persist one evaluated selection row.  Idempotent on (run_id, canonical_selection_id).
    Returns True on success.
    """
    try:
        conn = _get_conn()
        with conn:
            with conn.cursor() as cur:
                cur.execute(
                    """
                    INSERT INTO wow_daily_run_rows (
                        run_id, canonical_selection_id, market_version_id,
                        run_date, sport, player, prop, side, line, game_date,
                        terminal_bucket, classification, wow_score,
                        final_approval_blocker, audit_valid, side_resolution,
                        reconciliation_status, full_row
                    ) VALUES (
                        %s, %s, %s,
                        %s, %s, %s, %s, %s, %s, %s,
                        %s, %s, %s,
                        %s, %s, %s,
                        %s, %s
                    )
                    ON CONFLICT (run_id, canonical_selection_id) DO NOTHING
                    """,
                    (
                        run_id, canonical_selection_id, market_version_id,
                        run_date, sport, player, prop, side, line, game_date,
                        terminal_bucket, classification, wow_score,
                        final_approval_blocker, audit_valid, side_resolution,
                        reconciliation_status, json.dumps(full_row, default=str),
                    ),
                )
        conn.close()
        return True
    except Exception as exc:
        logger.error(
            "daily_manifest.save_run_row failed run=%s sel=%s: %s",
            run_id, canonical_selection_id, exc,
        )
        return False


