def create_run(
    *,
    run_id: str,
    run_date: str,
    started_at: str,
    environment: str,
    requested_sports: list[str],
    session_id: str | None = None,
    runtime_provenance: dict | None = None,
) -> bool:
    """
    Insert the run header row.  Idempotent — duplicate run_id is a no-op.
    Returns True on success, False on failure.
    """
    try:
        conn = _get_conn()
        with conn:
            with conn.cursor() as cur:
                cur.execute(
                    """
                    INSERT INTO wow_daily_runs
                        (run_id, run_date, started_at, environment,
                         requested_sports, session_id, runtime_provenance)
                    VALUES (%s, %s, %s, %s, %s, %s, %s)
                    ON CONFLICT (run_id) DO NOTHING
                    """,
                    (
                        run_id,
                        run_date,
                        started_at,
                        environment,
                        json.dumps(requested_sports),
                        session_id,
                        json.dumps(runtime_provenance) if runtime_provenance else None,
                    ),
                )
        conn.close()
        return True
    except Exception as exc:
        logger.error("daily_manifest.create_run failed for %s: %s", run_id, exc)
        return False


def _decode_run_row(row: dict[str, Any]) -> dict[str, Any]:
    for key in (
        "requested_sports", "scanned_sports", "missing_sports",
        "failed_modules", "runtime_provenance", "source_union_counts",
        "reconciliation", "discovery_checkpoint", "orchestration_metadata",
    ):
        if isinstance(row.get(key), str):
            try:
                row[key] = json.loads(row[key])
            except Exception:
                pass
    return row


def _run_date_text(value: Any) -> str:
    """Normalize DATE values returned by psycopg2 for identity comparison."""
    return value.isoformat() if hasattr(value, "isoformat") else str(value or "")


def create_or_get_run(
    *,
    run_id: str,
    idempotency_key: str | None,
    run_date: str,
    started_at: str,
    deadline_at: str,
    environment: str,
    requested_sports: list[str] | None,
    session_id: str | None = None,
    runtime_provenance: dict | None = None,
    run_timezone: str = "UTC",
    request_fingerprint: str | None = None,
) -> tuple[dict[str, Any] | None, bool]:
    """Atomically create or reuse one canonical run identity."""
    conn = _get_conn(acknowledgement=True)
    try:
        with conn:
            with conn.cursor() as cur:
                cur.execute(
                    """
                    INSERT INTO wow_daily_runs (
                        run_id, run_date, started_at, environment,
                        requested_sports, session_id, runtime_provenance,
                         idempotency_key, run_timezone, request_fingerprint,
                         deadline_at,
                        run_status, progress_stage, progress_updated_at
                    ) VALUES (
                        %s, %s, %s, %s, %s, %s, %s,
                        %s, %s, %s, %s, 'ACCEPTED', 'ACCEPTED', NOW()
                    )
                    ON CONFLICT DO NOTHING
                    RETURNING run_id
                    """,
                    (
                        run_id,
                        run_date,
                        started_at,
                        environment,
                        json.dumps(requested_sports or []),
                        session_id,
                        json.dumps(runtime_provenance)
                        if runtime_provenance else None,
                        idempotency_key,
                        run_timezone,
                        request_fingerprint,
                        deadline_at,
                    ),
                )
                created = cur.fetchone() is not None
                if idempotency_key:
                    cur.execute(
                        "SELECT * FROM wow_daily_runs "
                        "WHERE idempotency_key = %s LIMIT 1",
                        (idempotency_key,),
                    )
                else:
                    cur.execute(
                        "SELECT * FROM wow_daily_runs "
                        "WHERE run_id = %s LIMIT 1",
                        (run_id,),
                    )
                cols = [d[0] for d in cur.description]
                row = cur.fetchone()
                result = _decode_run_row(dict(zip(cols, row))) if row else None
                if result is not None and idempotency_key:
                    existing_date = _run_date_text(result.get("run_date"))
                    existing_timezone = str(result.get("run_timezone") or "UTC")
                    existing_fingerprint = result.get("request_fingerprint")
                    if existing_date != str(run_date) or existing_timezone != run_timezone:
                        raise ValueError("IDEMPOTENCY_KEY_INTENT_MISMATCH")
                    if (
                        request_fingerprint
                        and existing_fingerprint
                        and existing_fingerprint != request_fingerprint
                    ):
                        raise ValueError("IDEMPOTENCY_KEY_REQUEST_MISMATCH")
        return (
            result,
            created,
        )
    finally:
        conn.close()


def claim_run(
    run_id: str,
    execution_owner: str,
    *,
    lease_seconds: int = RUNNER_LEASE_SECONDS,
) -> bool:
    """Claim an accepted run exactly once with a durable runner lease."""
    if lease_seconds <= 0:
        raise ValueError("lease_seconds must be positive")
    conn = _get_conn(acknowledgement=True)
    try:
        with conn:
            with conn.cursor() as cur:
                cur.execute(
                    f"""
                    UPDATE wow_daily_runs
                    SET run_status = 'IN_PROGRESS',
                        progress_stage = 'STARTING',
                        progress_detail = 'Detached runner claimed run',
                        progress_updated_at = NOW(),
                        execution_owner = %s,
                        last_heartbeat_at = NOW(),
                        lease_expires_at = NOW() + INTERVAL '{int(lease_seconds)} seconds'
                    WHERE run_id = %s
                      AND run_status = 'ACCEPTED'
                      AND finished_at IS NULL
                    """,
                    (execution_owner, run_id),
                )
                return cur.rowcount == 1
    finally:
        conn.close()


def mark_progress(
    *,
    run_id: str,
    stage: str,
    detail: str | None = None,
    execution_owner: str | None = None,
) -> bool:
    """Persist lifecycle progress without changing scoring or row semantics."""
    conn = _get_conn()
    try:
        with conn:
            with conn.cursor() as cur:
                owner_fence = ""
                params: list[Any] = [stage, detail, run_id]
                if execution_owner is not None:
                    owner_fence = """
                      AND execution_owner = %s
                      AND lease_expires_at >= NOW()
                    """
                    params.append(execution_owner)
                cur.execute(
                    f"""
                    UPDATE wow_daily_runs
                    SET progress_stage = %s,
                        progress_detail = %s,
                        progress_updated_at = NOW()
                    WHERE run_id = %s
                      AND finished_at IS NULL
                      AND run_status IN ('ACCEPTED', 'IN_PROGRESS')
                    {owner_fence}
                    """,
                    tuple(params),
                )
                return cur.rowcount == 1
    finally:
        conn.close()


def persist_discovery_checkpoint(
    *,
    run_id: str,
    scanned_sports: list[str],
    missing_sports: list[str],
    total_discovered: int,
    source_union_counts: dict,
    discovery_checkpoint: dict,
    reconciliation_baseline: dict,
    execution_owner: str | None = None,
) -> bool:
    """Durably record the canonical board before evaluation can begin.

    The snapshot is intentionally immutable for the lifetime of a run.  It is
    the observability boundary between source discovery and scoring: a stalled
    scorer must never make a completed discovery look like an empty run.
    """
    conn = _get_conn()
    try:
        with conn:
            with conn.cursor() as cur:
                owner_fence = ""
                params: list[Any] = [
                    json.dumps(scanned_sports),
                    json.dumps(missing_sports),
                    total_discovered,
                    json.dumps(source_union_counts),
                    json.dumps(discovery_checkpoint, default=str),
                    json.dumps(reconciliation_baseline, default=str),
                    run_id,
                ]
                if execution_owner is not None:
                    owner_fence = """
                      AND execution_owner = %s
                      AND lease_expires_at >= NOW()
                    """
                    params.append(execution_owner)
                cur.execute(
                    f"""
                    UPDATE wow_daily_runs
                    SET scanned_sports = %s,
                        missing_sports = %s,
                        total_discovered = %s,
                        source_union_counts = %s,
                        discovery_checkpoint = %s,
                        reconciliation = %s,
                        progress_stage = 'DISCOVERY_PERSISTED',
                        progress_detail = 'Canonical board persisted before scoring',
                        progress_updated_at = NOW()
                    WHERE run_id = %s
                      AND finished_at IS NULL
                      AND run_status IN ('ACCEPTED', 'IN_PROGRESS')
                      AND discovery_checkpoint IS NULL
                    {owner_fence}
                    """,
                    tuple(params),
                )
                return cur.rowcount == 1
    finally:
        conn.close()


